<script>
    document.addEventListener('DOMContentLoaded', function() {

        const tick = `
        <svg xmlns="http://www.w3.org/2000/svg" width="16" height="16"
             viewBox="0 0 12 12" fill="none">
            <path d="M10 3L4.5 8.5L2 6"
                  stroke="#4A5565"
                  stroke-linecap="round"
                  stroke-linejoin="round"/>
        </svg>
    `;

        const tickElements = document.getElementsByClassName('tick');

        for (let i = 0; i < tickElements.length; i++) {
            tickElements[i].innerHTML = tick;
        }

    });
    document.querySelectorAll('.faq-btn').forEach(btn => {
        btn.addEventListener('click', () => {

            const item = btn.closest('.faq-item');
            const content = item.querySelector('.faq-content');
            const icon = btn.querySelector('.icon');
            const title = btn.querySelector('.faq-title');

            // Close others
            document.querySelectorAll('.faq-item').forEach(i => {
                if (i !== item) {
                    i.querySelector('.faq-content').style.maxHeight = null;
                    i.querySelector('.icon').textContent = '+';
                    i.querySelector('.faq-title').classList.remove('text-primary-light');
                }
            });

            // Toggle current
            if (content.style.maxHeight) {
                content.style.maxHeight = null;
                icon.textContent = '+';
                title.classList.remove('text-primary-light');
            } else {
                content.style.maxHeight = content.scrollHeight + "px";
                icon.textContent = '−';
                title.classList.add('text-primary-light');
            }
        });
    });
</script>
